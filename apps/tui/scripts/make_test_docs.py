"""Write the evaluator guide's flow pages from the test guide data (the /tests cases).

    python scripts/make_test_docs.py           # write docs/evaluator/*.md
    python scripts/make_test_docs.py --check   # exit 1 when a page is out of date

The cases live in reconix/store/test_guide/; change them there, never in the generated pages,
so the in-app checklist and the docs always say the same thing.
"""

import sys
from pathlib import Path
from typing import Dict, List, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from reconix.store import test_guide  # noqa: E402
from reconix.store.test_guide import cases_main  # noqa: E402
from reconix.store.test_guide.model import Case, Flow  # noqa: E402

DOCS = Path(__file__).resolve().parents[1] / "docs" / "evaluator"
HEADER = ("<!-- Generated by apps/tui/scripts/make_test_docs.py from "
          "reconix/store/test_guide/. Do not edit by hand. -->")

PAGES = (
    ("FLOW-0-SETUP.md", "Flow 0 · Set provider (first screen)", ("PROV",)),
    ("FLOW-1-MAIN.md", "Flow 1 · The main flow, one template at a time",
     ("MF-WEB", "MF-API", "MF-NET", "MF-SRC")),
    ("FLOW-2-CHAT.md", "Flow 2 · Chat (mock model and the step rules)", ("CHAT", "RULE")),
    ("FLOW-3-COMMANDS.md", "Flow 3 · Commands and settings", ("CMD",)),
    ("FLOW-4-LOCAL-WEB.md", "Flow 4 · Local web from the TUI", ("WEB", "WEB-AI")),
)


def _esc(text: str) -> str:
    return text.replace("|", "\\|")


def _case(case: Case) -> List[str]:
    lines = [f"#### {case.id} · {case.title}", ""]
    if case.note:
        lines += [f"> {case.note}", ""]
    if case.ask:
        lines += ["**Type this:**", "", "```text", case.ask, "```", ""]
    lines += [f"{n}. {step}" for n, step in enumerate(case.steps, 1)]
    lines += ["", f"**Expected:** {case.expect}", "", "Result: ☐ Pass ☐ Fail ☐ Skip", ""]
    return lines


def _flow(flow: Flow) -> List[str]:
    lines = [f"## {flow.number} {flow.title}", ""]
    lines += [f"{line}" for line in flow.intro] + [""] if flow.intro else []
    if flow.facts:
        lines += ["| What this template sets up | |", "|---|---|"]
        lines += [f"| {_esc(k)} | {_esc(v)} |" for k, v in flow.facts] + [""]
    for case in flow.cases:
        lines += _case(case)
    return lines


def page(title: str, flow_ids: Sequence[str]) -> str:
    by_id: Dict[str, Flow] = {f.id: f for f in test_guide.list_flows()}
    lines = [HEADER, "", f"# {title}", "",
             "Back to the guide: [README.md](README.md) · all cases: [TEST-CASES.md]"
             "(TEST-CASES.md). Mark each case in the app with `/tests` (p / f / s).", ""]
    if "MF-WEB" in flow_ids:
        lines += ["Every template walks the same gates, in this order:", "",
                  "| Gate | What you see and choose |", "|---|---|"]
        lines += [f"| {_esc(k)} | {_esc(v)} |" for k, v in cases_main.GATES]
        lines += ["", "**Test values:** any password (it never shows) and the one-time code "
                  "`123456`. Type `/new` before each case.", ""]
    for flow_id in flow_ids:
        lines += _flow(by_id[flow_id])
    return "\n".join(lines).rstrip() + "\n"


def cases_table() -> str:
    lines = [HEADER, "", "# All test cases", "",
             f"{len(test_guide.all_cases())} cases. The same list is in the app: type `/tests`.",
             "", "| Case | Flow | Title | Type this | Expected |", "|---|---|---|---|---|"]
    for flow in test_guide.list_flows():
        for case in flow.cases:
            ask = f"`{case.ask}`" if case.ask else ""
            lines.append(f"| {case.id} | {flow.number} {_esc(flow.title)} | {_esc(case.title)}"
                         f" | {_esc(ask)} | {_esc(case.expect)} |")
    return "\n".join(lines) + "\n"


def not_in_static() -> str:
    lines = [HEADER, "", "# Not in the static version", "",
             "Do not mark these as failures: the static TUI does not do them. They belong to "
             "the Core API (`services/api`) or the AI version (reconix-ai).", ""]
    lines += [f"- {item}" for item in test_guide.NOT_IN_STATIC]
    return "\n".join(lines) + "\n"


def build() -> Dict[str, str]:
    out = {name: page(title, ids) for name, title, ids in PAGES}
    out["TEST-CASES.md"] = cases_table()
    out["NOT-IN-STATIC.md"] = not_in_static()
    return out


def main(argv: Sequence[str]) -> int:
    stale = []
    for name, text in build().items():
        path = DOCS / name
        if "--check" in argv:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
            continue
        DOCS.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote docs/evaluator/{name}")
    if stale:
        print("out of date (run scripts/make_test_docs.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
